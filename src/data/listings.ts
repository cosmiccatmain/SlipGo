export type ListingType = "marina" | "yacht-club" | "guest-dock";
export type ListingMode = "rent" | "sale";
// Harbor regions live in one table (data/regions.ts) so adding a harbor is a
// single edit — estimate anchors, safety sources and trip waypoints all derive
// from it.
export type { Region } from "./regions";
import type { Region } from "./regions";

export interface Listing {
  id: string;
  name: string;
  type: ListingType;
  /** "rent" (slip rentals / dues / guest docks) or "sale" (deeded slips for sale) */
  mode: ListingMode;
  /** Big price line shown on the card, e.g. "$795/mo" */
  priceLabel: string;
  /** Short label shown inside the map pin, e.g. "$795" */
  pinLabel: string;
  /** Normalized dollars used for price filtering, sorting + the estimate */
  sortPrice: number;
  address: string;
  /** Harbor region key (map grouping + estimate location anchor). */
  region: Region;
  /** Human "where your boat actually sits" label, e.g. "Bora Bora Basin · Marina del Rey". */
  neighborhood: string;
  lat: number;
  lon: number;
  maxLengthFt: number;
  slipsOpen: number;
  /** Middle spec, e.g. "$19.50/ft" or "Members only" */
  rateNote: string;
  /** Trailing spec chip, e.g. "Liveaboard OK" */
  perk: string;
  /** Small all-caps attribution line, Zillow-style */
  attribution: string;
  /** Index into the photo palette rotation */
  photoSeed: number;
  /** Sample star rating (illustrative MVP data) */
  rating: number;
  /** Sample review count (illustrative MVP data) */
  reviewCount: number;
  /** Amenity tags — power the "More" filter and the value estimate */
  amenities: string[];
  /**
   * Curated fallback to the operator's official website. Google Places'
   * websiteUri is preferred at runtime; this only fills in when Google has
   * none. Add ONLY verified URLs — leave undefined rather than guessing.
   */
  website?: string;
  /**
   * Transient/overnight rate in $ per foot per night (guest docks & moorings).
   * Powers the SlipGo Trips cost estimator.
   */
  nightlyPerFt?: number;
}

